D = dt.date


def d(s):
    m, dd = s.split("/")
    return (int(m), int(dd))


def dates(y, a, b):
    """'10/1' 形式の a〜b の日付列。年度またぎなし（10〜11 月）。"""
    ma, da = d(a)
    mb, db = d(b)
    x = D(y, ma, da)
    e = D(y, mb, db)
    out = []
    while x <= e:
        out.append(x)
        x += dt.timedelta(days=1)
    return out



def task_days(t, year, actual=True):
    s, e = (t[6] or t[5]) if actual else t[5]
    out = []
    for x in dates(year, s, e):
        out.append(x)
    return out


def daily_rows(tasks, year, seed_add=0):
    """日付 → [(task, 記述, 人数, 時間)]。日曜は休工（運転・冷却を除く）。"""
    r = random.Random(SEED + seed_add)
    days = {}
    for t in tasks:
        steps = t[9]
        ds = task_days(t, year)
        si = 0
        for x in ds:
            sunday = x.weekday() == 6
            if t[3] == "SPC運転":
                desc = steps[si] if si < len(steps) else ""
                si += 1
                days.setdefault(x, []).append((t, desc, 0, 0))
                continue
            if sunday:
                continue
            desc = steps[si] if si < len(steps) else ""
            si += 1
            men = t[4]
            if men >= 4:
                men += r.choice([0, 0, 0, -1, 1])
            hrs = 8.0
            if "立会のため 午後のみ" in desc:
                hrs = 4.0
            elif r.random() < 0.15:
                hrs = 9.5
            if "未着" in desc:
                hrs = 8.0
            days.setdefault(x, []).append((t, desc, men, hrs))
    return dict(sorted(days.items()))

class Eq:
    __slots__ = ("no", "cat", "name", "spec", "maker", "imp", "strat", "role", "f",
                 "install", "policy", "alias", "key", "seq")

    def __init__(self, **kw):
        for k, v in kw.items():
            setattr(self, k, v)


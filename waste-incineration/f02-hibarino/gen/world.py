def plan_work(e, y, version):
    """version 年度の改訂版で、y 年度に計画された作業。"""
    if version < DECISION_YEAR:
        w = base_work(e, y)
        for yy in PROPOSAL_REPLACE.get((e.name, e.f), []):
            if yy == y:
                w.add("X")
    else:
        w = base_work(e, y)
        # 廃止決定後：最終 2 年度は法定・重要度 A の点検だけ、分解整備は 2028 以降は A のみ
        if y >= 2030:
            w = {"I"} if e.policy == "法定点検継続" else set()
        elif y >= 2029:
            w = {x for x in w if x == "I"} if e.imp == "A" or e.policy == "法定点検継続" else set()
        elif y >= 2027:
            if e.imp != "A":
                w.discard("O")
            if e.imp == "C":
                w.discard("I")
        if e.policy == "事後保全" and y >= 2019:
            w = set()
        for yy in PROPOSAL_REPLACE.get((e.name, e.f), []):
            if yy == y and yy < 2027:
                w.add("X")
            elif yy == y:
                w.add("R")             # 2027 以降の更新は補修に置換え
                w.discard("O")
    sp = SPECIAL.get((e.name, e.f), {})
    if y in sp:
        known = {
            ("過熱器", 1): 2025, ("ボイラ本体", 2): 2023, ("灰押出装置", 1): 2024, ("誘引通風機", 1): 2023,
            ("ボイラ給水ポンプB", 1): 2023, ("混練機", 0): 2024, ("ごみクレーン1号", 0): 2024,
            ("ボイラ本体", 1): 2025, ("燃焼ストーカ", 1): 2023, ("燃焼ストーカ", 2): 2024, ("煙突内筒", 2): 2020,
        }.get((e.name, e.f), 2016)
        if version >= known:
            w = set(sp[y])
    # 1号 BF ろ布：2024 抜取試験の結果で 2025→2026 へ延伸（2025 年度改訂から）
    if (e.name, e.f) == ("バグフィルタ", 1) and version >= 2025:
        if y == 2025:
            w.discard("X")
        if y == 2026:
            w.add("X")
    return w



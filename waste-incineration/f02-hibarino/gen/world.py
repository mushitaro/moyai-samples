def _phase(e):
    # 2 号炉は 1 号炉と半周期ずらす。共通設備は資産番号の連番で位相を散らす。
    return (e.seq + (1 if e.f == 2 else 0) * 1) % 7


def base_work(e, y):
    """保全の型から出る年度の作業（記号のもとになる集合）。廃止決定前の考え方。"""
    s = STRAT[e.strat]
    w = set()
    ph = _phase(e)
    if s.get("i"):
        if s["i"] == 1 or (y + ph + s.get("ph", 0)) % s["i"] == 0:
            w.add("I")
    off_o = 2 if e.f == 2 else (e.seq if e.f == 0 else 0)
    off_r = 1 if e.f == 2 else (e.seq * 2 if e.f == 0 else 0)
    if s.get("o"):
        if (y - 2016 + s.get("oph", 0) + off_o) % s["o"] == 0:
            w.add("O")
    if s.get("r"):
        if (y - 2016 + s.get("rph", 0) + off_r) % s["r"] == 0:
            w.add("R")
    if e.role == "予備" and "O" in w and _pair_has_o(e, y):
        w.discard("O")          # 予備機は常用機と同じ年に分解しない
    return w


def _pair_has_o(e, y):
    other = e.name[:-1] + "A"
    k = f"{other}#{e.f}"
    if k not in BYKEY:
        return False
    return "O" in base_work(BYKEY[k], y)



def oh_month(f, y, seq=0):
    """その年度の定修の月。1 号炉は偶数年度が秋、2 号炉は奇数年度が秋。共通設備は散らす。"""
    if f == 0:
        return [7, 10, 5, 11, 1, 8][seq % 6]
    autumn = (f == 1 and y % 2 == 0) or (f == 2 and y % 2 == 1)
    return 10 if autumn else 5



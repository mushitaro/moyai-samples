def names(items, limit=3):
    nm = []
    for x in items:
        e = core.get().by_tag[x["tag"]]
        nm.append(e["name"])
    if not nm:
        return ""
    if len(nm) > limit:
        return "、".join(nm[:limit]) + f" ほか {len(nm) - limit} 台"
    return "、".join(nm)


def line_text(ln, style="m3"):
    t = ln["task"]
    tt = t["type"]
    i, n = ln["day_index"], ln["n_days"]
    r = core.rng("tx", t["id"], i)
    if tt in TURB:
        arr = TURB[tt]
        txt = arr[min(i, len(arr) - 1)] if n <= len(arr) else arr[i % len(arr)]
    elif tt in KIKAN_T:
        arr = KIKAN_T[tt]
        txt = arr[min(len(arr) - 1, int(i * len(arr) / n))]
        if ln["items"]:
            txt += "（" + names(ln["items"], 2) + "）"
    else:
        ph = T.get(tt, [["{eq} 作業"]])
        p = ph[0] if i == 0 else (ph[-1] if i == n - 1 else ph[min(1, len(ph) - 1)])
        if len(ph) > 2 and 0 < i < n - 1:
            p = ph[1]
        txt = r.choice(p)
        eq = names(ln["items"]) or t["name"].split("（")[0]
        txt = txt.format(eq=eq, n=r.choice([4, 6, 8, 12, 24, 36, 48, 96, 120]) if "{n}" in txt else 0, t=r.choice([48, 52, 55]),
                         w=r.choice([2.6, 3.1, 3.8, 4.2]), a=r.choice([1.2, 1.6, 2.1, 2.4, 3.2]), r=min(6, i + 1))
    if ln.get("episode"):
        txt += "。" + ln["episode"][4]
    if style == "m1":
        txt = txt.replace("、", "・").split("。")[0]
        if len(txt) > 26:
            txt = txt[:26]
    elif style == "m2":
        txt = txt.split("。")[0] if not ln.get("episode") else txt
    return txt



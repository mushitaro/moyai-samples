def result(w):
    """報告書の結果・処置"""
    k = w["kind"]
    e = core.get().by_tag[w["tag"]]
    r = core.rng("res", w["tag"], w["fy"])
    # 翌年度に「前年度点検の指摘による補修」がある → この年は要注意
    nxt = [y for y in __import__("world").findings(e) if y == w["fy"]]
    if k == "I":
        if nxt:
            return "要注意（摩耗・劣化の進行）", "次年度 補修を提案"
        return r.choice(RESULT_I), "—"
    if k == "O":
        if "指摘" in w["note"]:
            return "前年度指摘箇所 補修", "補修 完了"
        return "分解整備 実施", r.choice(["部品交換 完了", "整備 完了", "消耗品交換 完了"])
    if k == "R":
        return "更新・交換", "交換 完了"
    return "基幹改良で更新", "更新 完了"



class Equip:
    def __init__(self, cat, name, units, spec, inst, renew, remark, oldpfx, unit, seq):
        self.cat, self.name, self.units, self.spec = cat, name, units, spec
        self.inst, self.renew, self.remark = inst, renew, remark
        self.unit = unit  # "1" / "2" / "共通"
        self.seq = seq
        u = {"1": "1", "2": "2", "共通": "0"}[unit]
        self.no = "%s%s-%02d" % (u, cat, seq)           # l1 が 2019 に付けた台帳番号
        # 完成図書の番号（竣工 S63 は朝凪炉工の機器表、H14 は DXN 対策の機器表）
        if oldpfx == "D14":
            self.oldno = "D14-%s%02d" % ({"1": "1", "2": "2", "共通": "C"}[unit], seq)
        else:
            self.oldno = "%s-%s%02d" % (cat, {"1": "1", "2": "2", "共通": "0"}[unit], seq)
        self.key = self.no

    @property
    def label(self):
        return ("%s号炉 " % self.unit if self.unit in ("1", "2") else "") + self.name


def build_equipment():
    eq = []
    for cat in CAT_ORDER:
        pf = [r for r in PER_FURNACE if r[0] == cat]
        cm = [r for r in COMMON if r[0] == cat]
        for u in ("1", "2"):
            for i, r in enumerate(pf, 1):
                inst, renew = r[4], r[5]
                if u == "2" and "H22/H23" in renew:
                    renew = renew.replace("H22/H23", "H23")
                elif u == "1" and "H22/H23" in renew:
                    renew = renew.replace("H22/H23", "H22")
                eq.append(Equip(r[0], r[1], r[2], r[3], inst, renew, r[6], r[7], u, i))
        for i, r in enumerate(cm, 1):
            eq.append(Equip(r[0], r[1], r[2], r[3], r[4], r[5], r[6], r[7], "共通", i))
    return eq


EQUIP = build_equipment()
EQ = {e.no: e for e in EQUIP}

def find(unit, name):
    for e in EQUIP:
        if e.unit == unit and e.name == name:
            return e
    raise KeyError((unit, name))


def counts():
    rows = len(EQUIP)
    units = sum(e.units for e in EQUIP)
    pf = {u: (sum(1 for e in EQUIP if e.unit == u), sum(e.units for e in EQUIP if e.unit == u)) for u in ("1", "2", "共通")}
    return rows, units, pf


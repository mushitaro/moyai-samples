def tree_order(items):
    """設備 → 号炉 → 系統（初出の順）→ 機器 の順に並べる（系統の結合を続けるため）。"""
    order = list(SETSUBI)
    first = {}
    for k, it in enumerate(items):
        first.setdefault((it["setsubi"], it["line"], it["keitou"]), k)
    return sorted(items, key=lambda e: (order.index(e["setsubi"]), e["line"],
                                        first[(e["setsubi"], e["line"], e["keitou"])], items.index(e)))


def _duty(spec, k):
    """「常用・予備」とある機器は No.1 常用、No.2 予備。"""
    if "常用・予備" in spec:
        return "常用" if k == 0 else "予備"
    return ""



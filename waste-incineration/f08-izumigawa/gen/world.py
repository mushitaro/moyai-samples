def build_removed_and_tags(items):
    """図書番号を振り、撤去した竣工時の機器（台帳の旧番号）を作る。撤去機器は管理対象に数えない。"""
    removed = []
    seq = {}
    dx = {}
    for it in items:
        key = (it["setsubi"], it["line"])
        L = TAGL[it["setsubi"]]
        if it["year"] == 1989 or it["base"] in REPLACED:
            seq[key] = seq.get(key, 0) + 1
            orig = f"{L}-{it['line']}{seq[key]:02d}"
            if it["year"] == 1989:
                it["tag"] = orig
            else:
                removed.append(dict(tag=orig, line=it["line"], setsubi=it["setsubi"], keitou=it["keitou"],
                                    name=it["name"].replace(it["base"], REPLACED[it["base"]]),
                                    base=REPLACED[it["base"]], removed_fy=it["year"], by=it["id"]))
                it["old_tag"] = orig
        if it["year"] != 1989:
            pre = {1999: "DX", 2008: "KR", 2009: "KR"}.get(it["year"])
            if pre:
                k2 = (pre, it["line"])
                dx[k2] = dx.get(k2, 0) + 1
                it["tag"] = f"{pre}-{it['line']}{dx[k2]:02d}"
            else:
                it["tag"] = ""
    return removed


def build_equipment():
    """318 台を作る。機器番号は i1 の付け方：炉＋設備コード＋連番（例 2B-007、共通は 0A-001）。"""
    items = []
    for line in (1, 2):
        seq = {}
        for (s, kei, name, n, year, imp, mk, spec) in LINE:
            for k in range(n):
                seq[s] = seq.get(s, 0) + 1
                nm = name if n == 1 else f"{name} No.{k + 1}"
                yr = 2007 + line if year in (2008, 2009) else year   # 部分改良：1号炉 H20、2号炉 H21
                items.append(dict(id=f"{line}{s}-{seq[s]:03d}", line=line, setsubi=s,
                                  keitou=kei, base=name, name=nm, year=yr, imp=imp,
                                  maker=MAKERS[mk], spec=spec, duty=_duty(spec, k)))
    seq = {}
    for (s, kei, name, n, year, imp, mk, spec) in COMMON:
        for k in range(n):
            seq[s] = seq.get(s, 0) + 1
            nm = name if n == 1 else f"{name} No.{k + 1}"
            items.append(dict(id=f"0{s}-{seq[s]:03d}", line=0, setsubi=s, keitou=kei,
                              base=name, name=nm, year=year, imp=imp, maker=MAKERS[mk],
                              spec=spec, duty=_duty(spec, k)))
    r = rng("serial")
    for it in items:
        it["serial"] = f"{r.randint(10, 99)}{r.choice('ABCKMT')}-{r.randint(1000, 9999)}"
    nl = sum(1 for i in items if i["line"] == 1)
    nc = sum(1 for i in items if i["line"] == 0)
    assert nl == 95 and nc == 128 and len(items) == 318, (nl, nc, len(items))
    global REMOVED
    REMOVED = build_removed_and_tags(items)
    return items



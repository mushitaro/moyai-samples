# 予備区分（常用・予備）
def standby_of(name):
    if '（B）' in name or '（2号）' in name and ('クレーン' in name or '空気圧縮機' in name or 'バケット' in name):
        return '予備'
    if '（A）' in name or '（1号）' in name and ('クレーン' in name or '空気圧縮機' in name or 'バケット' in name):
        return '常用'
    return ''


def build_machines():
    ms = []
    nos = {}
    for k in (1, 2):
        for (s, name, old, spec, kw, mk, cls) in PER_FURNACE:
            key = (k, s)
            nos[key] = nos.get(key, 0) + 1
            ms.append(dict(tag=f'{k}{s}-{nos[key]:02d}', name=name, old=(old if old != '-' else None),
                           furnace=k, sys=s, spec=spec, kw=kw, maker=mk, cls=cls))
    for (s, name, old, spec, kw, mk, cls) in COMMON:
        key = (0, s)
        nos[key] = nos.get(key, 0) + 1
        ms.append(dict(tag=f'0{s}-{nos[key]:02d}', name=name, old=(old if old != '-' else None),
                       furnace=0, sys=s, spec=spec, kw=kw, maker=mk, cls=cls))
    rnd = random.Random(SEED)
    for m in ms:
        m['standby'] = standby_of(m['name'])
        m['inst'] = '2001-03'
        m['renew'] = None   # 更新年度
        m['status'] = '休止' if m['cls'] == 'idle' else '稼働'
        if m['old'] is None and m['cls'] == 'dcs':
            m['inst'] = '2024-02'  # R5 基幹改良で新設（DCS）
        m['serial'] = f"{rnd.randint(1000, 9999)}-{rnd.randint(10, 99)}"
    # 既知の更新履歴（2001 以降、資料の外にある過去も含む正解）
    def set_(name, k, **kw):
        for m in ms:
            if m['name'] == name and m['furnace'] == k:
                m.update(kw); return m
        raise KeyError(name)
    set_('計量機（入口）', 0, inst='2015-11', renew=2015)
    set_('計量機（出口）', 0, inst='2015-11', renew=2015)
    set_('計量データ処理装置', 0, inst='2015-11', renew=2015)
    set_('空気圧縮機（2号）', 0, inst='2018-10', renew=2018)
    set_('無停電電源装置', 0, inst='2017-10', renew=2017)
    set_('直流電源装置', 0, inst='2014-10', renew=2014)
    set_('排ガス分析計', 1, inst='2012-10', renew=2012)
    set_('排ガス分析計', 2, inst='2012-10', renew=2012)
    # 基幹改良 R4（1号炉＋DCS盤据付）、R5（2号炉＋DCS切替）
    kikan = ['火格子（乾燥段）', '火格子（燃焼段）', '火格子（後燃焼段）', '炉油圧ユニット', '減温塔', '噴射水ポンプ（A）',
             '噴射水ポンプ（B）', 'バグフィルタ', 'BF逆洗装置', 'BF加温装置', 'BF制御盤', '減温塔噴霧制御盤',
             '炉コントローラ（FCS）', '減温塔出口温度計', 'BF入口温度計', 'BF差圧計']
    for k, yr, ym in ((1, 2022, '2022-12'), (2, 2023, '2023-11')):
        for n in kikan:
            set_(n, k, inst=ym, renew=yr, kikan=True)
    for m in ms:
        if m['sys'] == 'S' and m['furnace'] == 0 and m['cls'] == 'dcs':
            m.update(inst='2024-02', renew=2023, kikan=True)
    return ms


MACHINES = build_machines()


def counts():
    per = {k: sum(1 for m in MACHINES if m['furnace'] == k) for k in (0, 1, 2)}
    return per, len(MACHINES)


def old_machines():
    """2021 旧台帳の並び（新設 DCS 3 台なし、旧 DCS 5 台あり → 285 台）"""
    res = []
    for m in MACHINES:
        if m['sys'] == 'S' and m['furnace'] == 0 and m['cls'] == 'dcs':
            continue
        if m['old'] is None:
            m['old'] = m['name']   # 旧台帳も同じ名前で載せていた
            m['old_same'] = True
        res.append(m)
    # 旧 DCS を S の先頭へ
    olds = [dict(tag=None, name=None, old=o[2], furnace=0, sys='S', spec=o[3], kw=None, maker=o[5], cls='dcs',
                 standby='', inst='2001-03', renew=None, status='稼働', serial='-', olddcs=True) for o in OLD_DCS]

    order = {k: i for i, k in enumerate(SYS_ORDER)}
    for i, d in enumerate(eq):
        d['_i'] = i
    eq.sort(key=lambda d: (order[d['sys']], {1: 0, 2: 1, 0: 2}[d['f']], d['_i']))
    # a3 機器コード（2019年改訂）: 号炉-設備-連番
    cnt = {}
    for d in eq:
        k = (d['f'], d['sys'])

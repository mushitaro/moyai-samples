def _yrs(rule):
    if rule == 'odd': return lambda y: y % 2 == 1
    if rule == 'even': return lambda y: y % 2 == 0
    if rule == 'every': return lambda y: True
    if rule == 'tb': return lambda y: y in (2001, 2005, 2009, 2013, 2017, 2019, 2023, 2027, 2031)
    if rule == '3y': return lambda y: (y - 2010) % 3 == 0

def pick(opts, *keys):
    k = zlib.crc32("|".join(str(x) for x in keys).encode()) % len(opts)
    return opts[k]


def names(codes, n=3):
    nm = []
    for c in codes:
        e = BY_CODE.get(c)
        if not e:
            continue
        x = e["name"] if e["kind"] != "電動機" else e["name"].replace(" 電動機", "電動機")
        if x not in nm:
            nm.append(x)
    return "・".join(nm[:n]) + ("ほか" if len(nm) > n else "")



def phase_text(cat, i, n, codes, t, d):
    opts = T.get(cat, T["misc"])
    if n <= 1:
        stage = opts[0]
    else:
        idx = round(i * (len(opts) - 1) / (n - 1)) if n > 1 else 0
        stage = opts[min(idx, len(opts) - 1)]
    s = pick(stage, t["name"], d.isoformat())
    return s.replace("{n}", names(codes, 2) or t["name"].split("（")[0])


def task_day_codes(t, i, n):
    codes = t["codes"]
    if len(codes) > 6:
        return codes  # 多い場合は範囲で 1 行
    if n > 1 and len(codes) >= n:
        k = -(-len(codes) // n)
        part = codes[i * k:(i + 1) * k]
        return part or codes[-1:]
    return codes


def wdays(t, holi, cut=None):
    out = []
    d = t["as_"]
    while d <= t["ae"]:
        if (not off(d, holi)) or t["crew"] in ("SPC運転", "受変電"):
            if cut is None or d <= cut:
                out.append(d)
        d += timedelta(days=1)
    return out


def rows_for(c, d):
    """その日の行：dict(crew, no, text, codes, n, hrs, prog, note, task)"""
    out = []
    for t in c["tasks"]:
        days = wdays(t, c["holi"], c.get("cut"))
        if d not in days:
            continue
        if t["crew"] == "SPC運転" and "立上げ" not in t["name"] and "起動" not in t["name"]:
            continue
        i = days.index(d)
        n = len(days)
        cat = cat_of(t)
        codes = task_day_codes(t, i, n)
        text = phase_text(cat, i, n, codes, t, d)
        comp, leader, base = CREWS[t["crew"]]
        ppl = base + (1 if h(t["name"] + d.isoformat(), 7) == 0 else 0) - (1 if (h(t["name"] + d.isoformat(), 9) == 0 and base > 3) else 0)
        hrs = 8.0
        hk = h(c["key"] + t["name"] + d.isoformat(), 12)
        if hk == 0:
            hrs = 9.5
        elif hk == 1:
            hrs = 9.0
        elif n == 1 and cat in ("test", "panel", "wear", "hydro"):
            hrs = 4.0 if cat in ("test", "panel") else 8.0
        note = ""
        ev = t.get("event")
        if ev:
            kind, evd, txt = ev
            if d == evd:
                note = kind
                text = text + "／" + txt.split("→")[0].strip()
                if kind == "追加":
                    ppl += 2
            if d > t["pe"] and kind in ("手直し", "追加"):
                text = ("手直し：" if kind == "手直し" else "追加補修：") + txt.split("→")[-1].strip()
        prog = int(round(100 * (i + 1) / n / 5) * 5)
        if t["crew"] == "SPC運転":
            ppl, hrs = None, None
            note = "SPC運転"
        out.append(dict(crew=t["crew"] if t["crew"] != "SPC運転" else "SPC", no=t["no"], text=text, codes=codes, n=ppl,
                        hrs=(round(ppl * hrs * 2) / 2 if ppl else None), prog=prog, note=note, task=t))
    return out


WEATHER = ["晴", "晴", "曇", "晴", "雨", "曇", "晴", "曇時々雨", "晴", "晴のち曇"]


def weather(d):
    w = WEATHER[zlib.crc32(d.isoformat().encode()) % len(WEATHER)]
    if d.month == 6 and zlib.crc32(("r" + d.isoformat()).encode()) % 3 == 0:
        w = "雨"
    return w


def report_days(c):
    days = set()
    for t in c["tasks"]:
        if t["crew"] == "SPC運転":
            continue
        for d in wdays(t, c["holi"], c.get("cut")):
            days.add(d)
    return sorted(days)

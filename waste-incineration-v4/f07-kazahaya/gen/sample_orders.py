def write(fname, header, rows, fy, with_code, rate):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\r\n")
    w.writerow([f"#【架空】かざはや環境パートナーズ株式会社 会計システム KAIKEI-21 発注明細一覧 {fy}年度 "
                f"出力日 {'2019/04/08' if fy == 2018 else '2024/04/09'} 出力者 {'sp1' if fy == 2018 else 'sp2'}"])
    w.writerow(header)
    for r in rows:
        if with_code:
            (no, d, dept, acct, code, vcd, nm, spec, q, unit, up, due, kenshu, kind, who, note) = r
        else:
            (no, d, dept, acct, vcd, nm, spec, q, unit, up, due, kenshu, kind, who, note) = r
        amt = q * up
        tax = math.floor(amt * rate)
        row = [no, d, dept, acct] + ([code] if with_code else []) + [vcd, V[vcd], nm, spec, q, unit, up, amt, tax, due, kenshu, kind, who, note]
        w.writerow(row)
    with open(outpath(fname), "w", encoding="cp932", newline="") as f:
        f.write(buf.getvalue())
    return fname



def expand(rows, unit):
    """機器リストを 1 台ずつに展開。電動機は別の台として直後に置く。"""
    out = []
    seq = {}
    for (sys, cat, sub, name, suffixes, mkw, spec, imp, kind) in rows:
        for sfx in suffixes:
            seq[sys] = seq.get(sys, 0) + 10
            code = f"{unit}{sys}-{seq[sys]:03d}"
            if sfx == "":
                label = name
            elif sfx.isascii() or sfx.endswith("号"):
                label = f"{name}{sfx}"
            else:
                label = f"{name}（{sfx}）"
            if sfx in ("A", "B") and "常用・予備" in spec:
                role = "常用" if sfx == "A" else "予備"
            else:
                role = ""
            e = dict(code=code, unit=unit, sys=sys, cat=cat, sub=sub, name=label, base=name, sfx=sfx,
                     spec=spec, imp=imp, kind=kind, role=role, motor_of=None, kw=None)
            out.append(e)
            if mkw:
                v = "6.6kV" if mkw >= 200 else ("DC110V" if "直流電動機" in spec else "440V")
                m = dict(code=code + "M", unit=unit, sys=sys, cat=cat, sub=sub, name=f"{label} 電動機",
                         base=name + " 電動機", sfx=sfx, spec=f"{mkw}kW {v} {'4P' if mkw < 200 else '4P 高圧'}",
                         imp=imp, kind="電動機", role=role, motor_of=code, kw=mkw)
                out.append(m)
    return out


def build():
    f1 = expand(FURNACE, "1")
    f2 = expand(FURNACE, "2")
    c = expand(COMMON, "0")
    return f1, f2, c



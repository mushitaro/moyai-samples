def build_csv():
    fn = os.path.join(OUT, FN_CSV)
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator="\r\n", quoting=csv.QUOTE_MINIMAL)
    w.writerow(["【架空】さくら坂市 財務会計システム 支出負担行為・支出命令一覧", "所属:%s %s" % (SECT, SECT_N), "起票日:2022/04/01-2024/03/31", "出力日:2026/11/12 09:41"])
    head = ["年度", "伝票区分", "伝票番号", "起票日", "所属コード", "所属名", "款", "項", "目", "節", "節名称", "細節", "件名", "契約方法", "債権者コード", "債権者名", "金額", "支払予定日", "摘要"]
    allr = rows()
    blocks = [("＜支出負担行為（変更負担行為を含む）＞", [x for x in allr if x[1] != "支出命令"]),
              ("＜支出命令＞", [x for x in allr if x[1] == "支出命令"])]
    for bi, (label, rs) in enumerate(blocks):
        if bi:
            w.writerow([])
        w.writerow([label, "件数:%d" % len(rs)])
        w.writerow(head)
        tot = 0
        for fy, kind, no, d, km, sai, title, how, cr, amt, pay, memo in sorted(rs, key=lambda x: (x[3], x[2])):
            k = KAMOKU[km]
            c = CRED[cr]
            w.writerow([fy, kind, no, d, SECT, SECT_N, k[0], k[1], k[2], k[3], k[4], sai, title, how, c[0], c[1], amt, pay, memo])
            tot += amt
        w.writerow(["", "小計", "", "", "", "", "", "", "", "", "", "", "", "", "", "", tot, "", ""])
    with open(fn, "wb") as f:
        f.write(buf.getvalue().encode("cp932"))
    return fn



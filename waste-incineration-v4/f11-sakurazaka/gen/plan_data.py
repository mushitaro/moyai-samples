# l1 の概算（千円、税込）。当初計画の行ごとの費用は持たない（下の年度計だけ）

def _base_l1(e):
    n = e.name
    if e.no in SPECIFIC_L1:
        return dict(SPECIFIC_L1[e.no])
    if e.unit == "共通":
        return dict(COMMON_PLAN.get(n, {}))
    off = 0 if e.unit == "1" else 1
    d = {}
    if n in YEARLY:
        d = {y: "○" for y in YEARS}
    elif n in ALT:
        d = {y: "○" for y in YEARS if (y + off) % 2 == 0}
    if n in OH_ONCE:
        d[OH_ONCE[n] + (0 if e.unit == "1" else 1)] = "◎"
    if n in ("バグフィルタ本体",):
        pass
    if n in ("BFホッパヒータ",):
        d[2021 + off] = "○"
    if n in ("煙突内筒",):
        d[2022 + off] = "○"
    if n in ("BFバイパス煙道", "ボイラ出口煙道") and e.unit == "1":
        d[2021] = "○"
    return d

def l1_plan(e):
    d = _base_l1(e)
    # R9（廃止年度）は 2 号定修をしない前提：2 号は R9 空欄、1 号は点検のみ
    if 2027 in d:
        if e.unit == "2" or (d[2027] != "○" and e.unit != "共通"):
            del d[2027]
    return d


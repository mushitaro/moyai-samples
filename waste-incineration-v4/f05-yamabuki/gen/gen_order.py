def rdate(s):
    y, m, d = map(int, s.split('-'))
    return f'R{y-2018:02d}.{m:02d}.{d:02d}'


def trunc(s, n=20):
    return s if len(s) <= n else s[:n]


def build(path, year, rows, with_kouji):
    wb = Workbook(); ws = wb.active; ws.title = f'R{year-2018}支出負担行為一覧'
    props(wb, f'【架空】やまぶき広域処理組合 令和{year-2018}年度 支出負担行為一覧表（第二工場費）', '組合事務局 y1（財務会計システム出力）')
    cols = [('負担行為番号', 11), ('負担行為日', 10), ('節', 9), ('細節', 9), ('件名', 36)]
    if with_kouji:
        cols.append(('工事件名', 15))
    cols += [('相手方', 30), ('契約方法', 13), ('負担行為額', 13), ('変更後額', 13), ('支出済額', 13), ('残額', 11), ('支出日', 10), ('備考', 34)]
    for i, (t, w) in enumerate(cols, 1):
        ws.column_dimensions[L(i)].width = w
    nc = len(cols)
    put(ws, 1, 1, '【架空】支出負担行為一覧表', f(12, True, name=FONT_M))
    put(ws, 2, 1, f'会計年度：令和{year-2018:02d}年度　　会計：一般会計　　款：衛生費　項：清掃費　目：第二工場費', f(9, name=FONT_M))
    put(ws, 3, 1, f'所属：{UNION} 事務局　　出力日：令和{year-2017:02d}年05月31日　　出力者：y1', f(9, name=FONT_M))
    r = 5
    for i, (t, w) in enumerate(cols, 1):
        fl = fill('FFFF99') if t == '工事件名' else fill('C0C0C0')
        put(ws, r, i, t, f(9, True, name=FONT_M), AC, fl)
    if with_kouji:
        ws.cell(r, 6).comment = Comment('R5年度分から追加（y1）。システムの件名が20字で切れて工事の区別がつかないため手入力。', 'y1')
    box(ws, r, 1, r, nc)
    r += 1
    sums = {}
    for row in rows:
        (no, d, setsu, saisetsu, name, aite, how, amt, chg, chgd, pays, kouji, note) = row
        after = amt + chg
        paid = sum(a for _, a in pays)
        payd = '月次' if pays[0][0] == '毎月' else '・'.join(rdate(x) for x, _ in pays)
        vals = [no, rdate(d), setsu, saisetsu, trunc(name)]
        if with_kouji:
            vals.append(kouji)
        vals += [aite, how, amt, after if chg else None, paid, after - paid, payd,
                 (note + (f'（変更 {rdate(chgd)}）' if chg else '')).strip()]
        for i, v in enumerate(vals, 1):
            numeric = isinstance(v, int)
            put(ws, r, i, v, f(9, name=FONT_M), AR if numeric else AL, nf='#,##0' if numeric else None)
        sums.setdefault(setsu, [0, 0, 0])
        sums[setsu][0] += after; sums[setsu][1] += paid; sums[setsu][2] += after - paid
        r += 1
    box(ws, 6, 1, r - 1, nc, thin)
    r += 1
    ia = [c for c, _ in cols].index('変更後額') + 1
    label_c = [c for c, _ in cols].index('件名') + 1
    put(ws, r, label_c, '＜節別集計＞（変更後額）', f(9, True, name=FONT_M))
    r += 1
    tot = [0, 0, 0]
    for s in ('委託料', '工事請負費', '需用費', '役務費'):
        if s not in sums:
            continue
        put(ws, r, label_c, s, f(9, name=FONT_M), AL)
        for j, v in enumerate(sums[s]):
            put(ws, r, ia + j, v, f(9, name=FONT_M), AR, nf='#,##0')
            tot[j] += v
        r += 1
    put(ws, r, label_c, '合計', f(9, True, name=FONT_M), AL)
    for j, v in enumerate(tot):
        put(ws, r, ia + j, v, f(9, True, name=FONT_M), AR, nf='#,##0')
    box(ws, r - len([s for s in sums]), label_c, r, ia + 2)
    put(ws, r + 2, 1, '※ 負担行為額は税込の契約額（単価契約は予定額）。変更後額は変更契約のある行のみ表示。', f(8, name=FONT_M))
    ws.freeze_panes = 'C6'
    setup_print(ws, True, 8, 1, 0, f'A1:{L(nc)}{r+2}', '5:5')
    ws.oddFooter.center.text = '&P / &N'
    wb.save(path)



def preview(csv_path, enc):
    """PNG 確認用：CSV の各行をそのままセルに読み込んだ一時 xlsx を作り、横 A3 で描く（納品物は CSV のまま）。"""
    from openpyxl import Workbook
    from xlhelp import font, page
    raw = open(csv_path, "rb").read().decode(enc)
    lines = raw.splitlines()
    wb = Workbook()
    ws = wb.active
    ws.cell(row=1, column=1, value=lines[0]).font = font(8)
    for r, row in enumerate(csv.reader(lines[1:]), 2):
        for c, v in enumerate(row, 1):
            ws.cell(row=r, column=c, value=v).font = font(7)
    for c in range(1, ws.max_column + 1):
        mx = max(len(str(ws.cell(row=r, column=c).value or "")) for r in range(2, ws.max_row + 1))
        ws.column_dimensions[ws.cell(row=2, column=c).column_letter].width = min(max(mx * 1.3, 5), 40)
    page(ws, landscape=True, paper=8, fit_w=1, fit_h=0)
    tmp = os.path.join(WORK, os.path.splitext(os.path.basename(csv_path))[0] + "_preview.xlsx")
    wb.save(tmp)
    return render(tmp, [1], stem=os.path.splitext(os.path.basename(csv_path))[0])



def life_events(e, until=2040):
    """更新（REPLACE）の年度。過去分は実際に行った更新として扱う"""
    ins, ovh, life = POLICY.get(e.cls, DEFAULT_POLICY)
    ev = []
    if e.cls in DCS_CLS:
        ev.append(2019)
        y = 2019
    else:
        y = start_fy(e) - 1
    if life:
        y = y + life + (0 if e.cls in DCS_CLS else JIT[e.crit] + (2 if e.duty == "予備" else 0))
        while y <= until:
            ev.append(y)
            y += life
    return ev

def ovh_offset(e, ovh):
    off = (e.idx * 5 + e.furn * 2 + len(e.base)) % ovh
    if e.suffix == "B" and e.duty in ("交互", "予備"):
        off = (off + max(1, ovh // 2)) % ovh
    return off

def policy_marks(e, y0, y1):
    """方針どおりの印（I 点検 / O 整備 / R 更新）。計画を作る時点の考え方であり実績ではない"""
    ins, ovh, life = POLICY.get(e.cls, DEFAULT_POLICY)
    m = {}
    ren = life_events(e)
    for y in range(y0, y1 + 1):
        if y in ren:
            m[y] = "R"; continue
        if y < start_fy(e):
            continue
        if ovh:
            base = max([r for r in ren if r < y] + [start_fy(e) - 1])
            if (y - base - 1 - ovh_offset(e, ovh)) % ovh == 0 and y - base > 1:
                m[y] = "O"; continue
        if ins and (y - 2009) % ins == 0:
            m[y] = "I"
    return m


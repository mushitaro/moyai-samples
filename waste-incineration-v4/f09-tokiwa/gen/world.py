def build_equipment():
    eqs = []
    seqno = {}
    def add(sys, group, sub, base, cls, spec, suffix, duty, crit, furn):
        key = (furn, sys)
        seqno[key] = seqno.get(key, 0) + 1
        tag = f"{furn}-{sys}-{seqno[key]:02d}"
        name = base + (suffix if suffix.startswith("No.") or suffix in ("A", "B", "") or "-" in suffix else "") \
            if True else base
        if suffix and not (suffix.startswith("No.") or suffix in ("A", "B") or "-" in suffix):
            name = f"{suffix}{base}" if suffix.endswith("号") else f"{base}（{suffix}）"
        elif suffix:
            name = f"{base} {suffix}" if (suffix.startswith("No.") or "-" in suffix) else f"{base}{suffix}"
        else:
            name = base
        inst = "2009-03"
        e = Eq(tag=tag, sys=sys, group=group, sub=sub, base=base, suffix=suffix, name=name, cls=cls,
               spec=spec, furn=furn, duty=duty, crit=crit, install=inst,
               maker=SUBMAKER.get(cls, "【架空】鷹羽エンジニアリング"))
        eqs.append(e)
    for furn in (1, 2):
        for d in FURNACE_DEF:
            sys, group, sub, base, cls, spec, sfx, crit = d
            for s, duty in sfx:
                add(sys, group, sub, base, cls, spec, s, duty, crit, furn)
    for d in COMMON_DEF:
        sys, group, sub, base, cls, spec, sfx, crit = d
        for s, duty in sfx:
            add(sys, group, sub, base, cls, spec, s, duty, crit, 0)
    # 並べ順：設備グループ→炉→系統
    for i, e in enumerate(eqs):
        e.idx = i
        e.spc_no = f"TK-{(i * 7 + 1013) % 9000 + 1000:05d}"

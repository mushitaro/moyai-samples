def new_csv(path):
    buf = io.StringIO()
    w = csv.writer(buf, quoting=csv.QUOTE_ALL, lineterminator="\r\n")
    w.writerow(["【架空】ときわ北部エコサービス株式会社 購買システム 発注明細一覧", "期間:2025/04/01～2026/03/31", "出力:2026/04/06 sv2"])
    # 行種別 H＝発注ヘッダ（1 発注 1 行）、D＝明細行。列はヘッダと明細で意味を使い分ける（システムの出力仕様）
    w.writerow(["行種別", "発注番号", "明細No", "発注日／品目コード", "仕入先コード／品名", "仕入先名／規格・型式", "工事件名／数量", "勘定科目／単位",
                "合計金額(税抜)／単価", "消費税合計／金額(税抜)", "承認者／納入予定日", "設備タグ", "発注区分", "備考"])
    from collections import OrderedDict
    groups = OrderedDict()
    for row in NEW:
        groups.setdefault(row[0], []).append(row)
    for no, rows in groups.items():
        tot = sum(round(r[8] * r[10]) for r in rows)
        h = rows[0]
        w.writerow(["H", no, "", h[2], h[3], h[4], h[13], h[12], tot, round(tot * 0.1), "所長" if tot >= 1000000 else "sv2", "", "", ""])
        for (no_, ln, d, vc, vn, ic, hin, kik, q, u, tk, nk, ka, ko, tag, kb, bi) in rows:
            amt = round(q * tk)
            w.writerow(["D", no_, ln, ic, hin, kik, q, u, tk, amt, nk, tag, kb, bi])
    with open(path, "w", encoding="utf-8-sig", newline="") as fp:
        fp.write(buf.getvalue())
    return len(NEW)


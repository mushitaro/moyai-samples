def _mk(unit, sysmap, t, removed=None, added=None):
    sysno, typ, loop, name, spec, cls, imp, maker, ab = t
    big, sub = sysmap[sysno]
    out = []
    suffixes = [("A", "常用"), ("B", "予備")] if ab == "AB" else ([("A", "交互"), ("B", "交互")] if ab == "AB2" else [("", "—")])
    for suf, duty in suffixes:
        tag = f"{unit}-{typ}-{loop}{suf}"
        nm = name + (f"{suf}" if suf else "")
        out.append(dict(tag=tag, unit=unit, sysno=sysno, setsubi=big, keito=sub, type=typ, loop=loop,
                        name=nm, base_name=name, spec=spec, cls=cls, imp=imp, maker=maker, duty=duty,
                        installed=2004, removed=removed, added=added))
    return out


def build():
    eq = []
    for n in (1, 2, 3):
        u = str(n)
        uy = UPGRADE_YEAR_BY_FURNACE[n]
        for t in PER_FURNACE:
            rm = uy if (t[0], t[1], t[2]) in FURNACE_REMOVED_BY_UPGRADE else None
            eq += _mk(u, SYS_F, t, removed=rm)
        for (sysno, typ, loop, name, spec, cls, imp) in EXTRA_FURNACE_INST:
            eq += _mk(u, SYS_F, (sysno, typ, loop, name, spec, cls, imp, M_INS, None))
        for t in FURNACE_ADDED_BY_UPGRADE:
            for e in _mk(u, SYS_F, t):
                e["installed"] = uy
                e["added"] = uy
                eq.append(e)
    for t in COMMON:
        eq += _mk("C", SYS_C, t)
    for t in DCS_OLD_ONLY:
        eq += _mk("C", SYS_C, t, removed=DCS_UPGRADE_YEAR)
    for t in DCS_KEEP:
        eq += _mk("C", SYS_C, t)
    for t in DCS_NEW_ONLY:
        for e in _mk("C", SYS_C, t):
            e["installed"] = DCS_UPGRADE_YEAR
            e["added"] = DCS_UPGRADE_YEAR
            eq.append(e)
    for (sysno, typ, loop, name, imp) in COMMON_INST:
        eq += _mk("C", SYS_C, (sysno, typ, loop, name, "", "inst", imp, M_INS, None))
    # 後年追設
    for e in eq:
        if e["tag"] in ("C-CV-956", "C-HP-957"):
            e["installed"] = 2011
        if e["tag"] == "C-LOG-1118":
            e["installed"] = 2014
    tags = [e["tag"] for e in eq]
    assert len(tags) == len(set(tags)), "tag duplicate"
    return eq


def alive(e, fy):
    """fy 年度末時点で台帳にあるか（added/installed 年度に設置、removed 年度に撤去）"""
    if e["installed"] > fy:
        return False
    if e["removed"] is not None and e["removed"] <= fy:
        return False
    return True



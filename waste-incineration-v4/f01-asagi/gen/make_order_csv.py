def _cids(title, fy):
    t = title.replace(' ', '')
    ids = [w['id'] for w in TR.WORKS if w['fy'] == fy and w['contract'].replace(' ', '') == t]
    # 物品（支給品・予備品）は、それを使った作業へ結ぶ。未使用の予備品は空のまま
    if 'ろ布' in t:
        ids = [x['id'] for x in TR._BY[(fy, 'BF-101')] if 'ろ布' in x['text']]
    if '燃焼火格子片' in t:
        ids = TR.work_ids(fy, 'ST-102')
    if '押込送風機振動測定' in t:
        ids = TR.work_ids(fy, 'F-201', 'H')
    # 法定点検の委託は LEGAL の id で結ぶ
    from f01_master import LEGAL
    for key, lid in (('排ガス等測定', 'LG09'), ('作業環境測定', 'LG10'), ('電気保安', 'LG04'), ('クレーン', 'LG06'), ('計量機定期点検', 'LG11'),
                     ('消防用設備', 'LG12'), ('精密機能検査', 'LG13'), ('圧力容器', 'LG08')):
        if key in t:
            ids = ['%s-%d' % (lid, fy)] + (['LG07-%d' % fy] if key == 'クレーン' else [])
    return ids


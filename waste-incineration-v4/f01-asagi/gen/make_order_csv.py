def preview_png(hdr, rows, name, title):
    """CSV を表計算で開いた状態（行番号・列記号・枠線つき）の画像"""
    wb = Workbook(); ws = wb.active; ws.title = name[:30]
    ws.append(title)
    ws.append(hdr)
    for r in rows:
        ws.append(r)
    for c in range(1, len(hdr) + 1):
        L = max(len(str(ws.cell(row=i, column=c).value or '')) for i in range(2, min(len(rows) + 3, 40)))
        ws.column_dimensions[CL(c)].width = min(34, max(5, L * 1.6 + 1))
    for row in ws.iter_rows():
        for cell in row:
            cell.font = Font(name='ＭＳ Ｐゴシック', size=10)
    ws.print_options.gridLines = True
    ws.print_options.headings = True
    page(ws, landscape=True, paper=8, fith=1, area='A1:%s%d' % (CL(len(hdr)), len(rows) + 2), margins=(0.3, 0.3, 0.4, 0.4))
    p = TMP + '_x/' + name + '.xlsx'
    os.makedirs(TMP + '_x', exist_ok=True)
    wb.save(p)
    return render(p, pages=(1,))


def cost_of(fy, tag, contract):
    d = BYTAG[tag]
    return sum(c for (k, t, c, ct) in d['act'].get(fy, []) if ct == contract)

# 定期整備業務委託の契約額（税込）: 定額部分（共通仮設・清掃・法定点検対応・電気計装点検・試運転）＋個別整備分。支給品（ろ布）は除く
def teishu_amount(fy):
    base = {2011: 86000, 2025: 121000}.get(fy, 100000 + (fy - 2011) * 2500)
    t = sum(c for (dd, k, tx, c, ct) in events_in(fy) if ct == 'T')
    if fy in (2007, 2008, 2013, 2014, 2019, 2020, 2025):
        t -= 8250  # 市支給のろ布代を除く
    tax = 0.05 if fy < 2014 else (0.08 if fy < 2019 else 0.10)
    if fy == 2019:
        tax = 0.08
    return int(round((base + t) * 1000 * (1 + tax), -4))

def hoshu_amount(fy, tag, ratio=0.97):
    tax = 0.05 if fy < 2014 else (0.08 if fy < 2019 else 0.10)
    return int(round(cost_of(fy, tag, 'H') * 1000 * ratio * (1 + tax), -3))


def tasks_all(tasks):
    return [t for t in tasks]

def work_days(t):
    """作業日（日曜は休工。ただし運転操作・全停・冷却は日曜も）"""
    out = []
    x = t['s']
    while x <= t['e']:
        if x.weekday() != 6 or t['team'] == '運転' or t['grp'] == '全停':
            out.append(x)
        x += dt.timedelta(days=1)
    return out

def check_tags(tasks, fy):
    """工程のタグが、その年度の実績イベントと一致するか確認"""
    evtags = {d['tag'] for (d, k, t, c, ct) in events_in(fy)}
    used = set()
    for t in tasks:
        for g in t['tags']:
            assert g in evtags, (fy, t['no'], g)
            used.add(g)
    return evtags - used


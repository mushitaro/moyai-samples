# ------------------------------------------------- 計画の生成（版ごとに作成時点の情報だけ）
HEALTH_F = {4: 1.15, 3: 1.0, 2: 0.8, 1: 0.65}

def health_at(d, asof):
    """作成時点の健全度（4:健全 3:軽微 2:要注意 1:要対策）。最後の大きな整備からの経過と状態の乱れ。"""
    R = rng(d, 'h%d' % asof)
    majors = [y for y, v in d['act'].items() if y < asof and any(k in ('更新', '整備', '補修') for (k, *_r) in v)]
    base = max(majors) if majors else max(1997, d['inst'])
    age = asof - base
    s = 4 - (age >= 6) - (age >= 11) - (age >= 16)
    if not any(t[0] in ('更新', '整備', '補修') for t in tracks_for(d)):
        s = 3 if age < 20 else 2   # 点検だけの機器（盤など）は経年で 2 まで
    s += R.choice([0, 0, 0, 1, -1])
    return max(1, min(4, s))

def plan(d, asof, horizon, rules):
    """asof 年度当初に作る計画。asof 年度より前の実績だけを使う。"""
    R = rng(d, 'p%d' % asof)
    h = health_at(d, asof)
    fac = HEALTH_F[h]
    out = {}
    kik = {y: (k, t, c) for (y, k, t, c) in KIKAN.get(d['tag'], [])}
    for (kind, a, b, lo, hi, tx) in tracks_for(d):
        if d['method'] == 'BM' and kind != '更新' and kind != '補修':
            continue
        if d['method'] == 'BM':
            continue  # 事後保全は計画に載せない（空欄）
        hist = [y for y, v in d['act'].items() if y < asof and any(t == tx or t.startswith(tx[:4]) or (kind == '更新' and _k == '更新') for (_k, t, *_r) in v)]
        last = max(hist) if hist else max(1997, d['inst'])
        mid = (a + b) / 2.0 * fac
        y = int(round(last + mid))
        if y < asof:
            y = asof if R.random() < 0.6 else asof + 1   # 期限超過は早期に
        cap = {'C': 1, 'B': 2}.get(d['imp'], 99)   # 重要度の低い機器は直近の 1〜2 回だけ置く（先は状態を見て決める）
        nocc0 = 0
        while y <= horizon:
            if nocc0 >= cap:
                break
            nocc0 += 1
            ky = [k for k in kik if k >= asof and k <= y and k > last]
            if ky and rules.get('kikan', True):
                last = ky[0]
                y = int(round(last + (a + b) / 2.0))
                continue
            cost = int(round((lo + hi) / 2 / 100.0)) * 100
            if rules.get('end') and kind == '更新' and y > rules['end'] - 4:
                pass_ = True
            else:
                pass_ = False
            if not pass_:
                if rules.get('end') and y >= rules['end'] - 1 and kind not in ('点検', '計測'):
                    pass
                else:
                    out.setdefault(y, []).append((kind, tx, cost))
            last = y
            nocc = len([1 for v in out.values() for e in v if e[1] == tx])
            step = (a + b) / 2.0 * max(0.75, fac * (1 - 0.04 * nocc))
            if step >= 4:
                step += R.choice([-1, 0, 0, 0, 1])
            y = int(round(last + max(a if a > 0 else 1, step)))
    if rules.get('kikan', True):
        for y, (k, t, c) in kik.items():
            if y >= asof:
                for yy in (y - 2, y - 1):
                    if yy in out:
                        out[yy] = [e for e in out[yy] if e[0] in ('点検', '計測')]
                        if not out[yy]:
                            del out[yy]
                out[y] = [(k, t, c)]
    return out, h


import re as _re
def rotate(plans, asof, horizon, end=None):
    """同型の並列機（投入扉No.1〜6、空冷復水器ファン、BF室ダンパ、高圧盤 等）は、一度に全部をやらず毎年数台ずつ回す。"""
    groups = {}
    for d in EQ:
        key = _re.sub(r'(No\.\d+|第\d室|（[^）]*）)', '', d['name'])
        groups.setdefault((d['f'], key, d['prof']), []).append(d)
    for (f, key, prof), G in groups.items():
        if len(G) < 3:
            continue
        kinds = {}
        for d in G:
            for y, v in plans[d['code']].items():
                for e in v:
                    if '基幹' in e[1]:
                        continue
                    kinds.setdefault((e[0], e[1]), []).append(e[2])
        for (k, tx), costs in kinds.items():
            tr = [t for t in tracks_for(G[0]) if t[5] == tx]
            if not tr:
                continue
            per = max(2, int(round((tr[0][1] + tr[0][2]) / 2.0)))
            cost = int(round(sum(costs) / len(costs), -2))
            for i, d in enumerate(G):
                p = plans[d['code']]
                for y in list(p.keys()):
                    p[y] = [e for e in p[y] if not (e[0] == k and e[1] == tx)]
                    if not p[y]:
                        del p[y]
                y = asof + (i * per) // len(G)
                while y <= horizon:
                    if not (end and k not in ('点検', '計測') and y >= end - 1):
                        p.setdefault(y, []).append((k, tx, cost))
                    y += per
    return plans

def level(plans, asof, cap):
    """同一年度に両炉の大物が重なれば 2号炉側を 1 年送る。年度の上限を超えれば重要度 C→B の順で送る。"""
    for d in EQ:
        if d['f'] != 2:
            continue
        twin = next((e for e in EQ if e['f'] == 1 and e['name'] == d['name']), None)
        if not twin:
            continue
        p2, p1 = plans[d['code']], plans[twin['code']]
        y1 = {y for y, v in p1.items() if any('基幹' not in e[1] for e in v)}
        y2 = {y for y, v in p2.items() if any('基幹' not in e[1] for e in v)}
        if len(y1 & y2) >= 2:
            # 両炉が同じ年に並ぶ場合、2号炉側を 1 年ずらして定修の作業量をならす
            np_ = {}
            for y, v in p2.items():
                for e in v:
                    ny = y if '基幹' in e[1] else y + 1
                    if ny <= 2034:
                        np_.setdefault(ny, []).append(e)
            p2.clear(); p2.update(np_)
        for y in sorted(list(p2.keys())):
            big2 = [e for e in p2[y] if e[2] >= 5000 and '基幹' not in e[1]]
            big1 = [e for e in p1.get(y, []) if e[2] >= 5000 and '基幹' not in e[1]]
            if big2 and big1:
                p2.setdefault(y + 1, []).extend(big2)
                p2[y] = [e for e in p2[y] if e not in big2]
                if not p2[y]:
                    del p2[y]
    for it in range(3):
        tot = {}
        for d in EQ:
            for y, v in plans[d['code']].items():
                tot[y] = tot.get(y, 0) + sum(e[2] for e in v if '基幹' not in e[1])
        for y in sorted(tot):
            if tot[y] <= cap:
                continue
            over = tot[y] - cap
            for imp in ('C', 'B'):
                for d in EQ:
                    if over <= 0 or d['imp'] != imp:
                        continue
                    p = plans[d['code']]
                    mv = [e for e in p.get(y, []) if '基幹' not in e[1] and e[0] in ('整備', '補修', '更新')]
                    if mv:
                        p.setdefault(y + 1, []).extend(mv)
                        p[y] = [e for e in p[y] if e not in mv]
                        if not p[y]:
                            del p[y]
                        over -= sum(e[2] for e in mv)
    return plans

